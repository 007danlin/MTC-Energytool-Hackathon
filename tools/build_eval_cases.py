def g(*refs):
    """'S27' -> '20-products/23-solar.md#s027'"""
    out = []
    for r in refs:
        key = r.rstrip('0123456789')
        out.append(f"{D[key]}#s{int(r[len(key):]):03d}")
    return out


def dlg(*turns):
    return "\n".join(("Пользователь: " if i % 2 == 0 else "Ассистент: ") + t for i, t in enumerate(turns))


