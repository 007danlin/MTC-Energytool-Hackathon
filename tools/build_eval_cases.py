def main():
    repo = Path(sys.argv[1])
    ids = {f.source_id for f in load_fragments(repo / 'data/knowledge-base.zip')}
    bad = [(i, s) for i, c in enumerate(C) for grp in c['groups'] for s in grp if s not in ids]
    if bad:
        raise SystemExit(f'Unknown source ids: {bad}')
    out = []
    for i, c in enumerate(C, 1):
        # Deterministic holdout: every 4th case is not used while tuning.
        out.append({'id': f'e{i:03d}', 'split': 'holdout' if i % 4 == 0 else 'dev', **c})
    path = repo / 'data/eval/retrieval_cases_v2.json'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf8')
    from collections import Counter
    print(len(out), 'cases ->', path)
    print('topics', dict(Counter(c['topic'] for c in out)))
    print('types', dict(Counter(c['type'] for c in out)))
    print('splits', dict(Counter(c['split'] for c in out)))
    print('docs covered', len({s.split('#')[0] for c in out for grp in c['groups'] for s in grp}), 'of 19')


main()
