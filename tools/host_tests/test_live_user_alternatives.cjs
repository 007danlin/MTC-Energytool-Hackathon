// Live browser audit without LLM calls or API mocks. Creates only its own demo sessions.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WEB_TEST_URL || 'http://127.0.0.1:8768';
const out = process.env.WEB_TEST_SHOTS || path.resolve('reports/live-user-audit-20261115/secondary');
if (!/^http:\/\/(127\.0\.0\.1|localhost):/.test(base)) throw Error('Local audit only');
fs.mkdirSync(out,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true});
  const result={started_at:new Date().toISOString(),base,scenarios:[],observations:[],screenshots:[],llm_requests:0,errors:[]};
  try {
    const page=await browser.newPage({viewport:{width:1440,height:960},locale:'ru-RU'});
    page.on('pageerror',e=>result.errors.push(e.message));
    page.on('request',r=>{if(r.method()==='POST' && /\/sessions\/[^/]+\/messages$/.test(new URL(r.url()).pathname))result.llm_requests++;});
    const button=name=>page.getByRole('button',{name,exact:true});
    const input=page.locator('#et-question');
    const idle=()=>page.waitForFunction(()=>{const h=document.querySelector('#energytool-chat'),q=document.querySelector('#et-question');return h&&q&&!q.disabled&&!['waiting','sync'].includes(h.dataset.screen);});
    const activeID=()=>page.evaluate(()=>localStorage.getItem('energytool-session'));
    const snap=async name=>{await page.evaluate(()=>document.fonts.ready);const file=path.join(out,name+'.png');await page.screenshot({path:file});result.screenshots.push(file);};
    const menu=()=>button('Меню').click();
    const contacts=async()=>{await menu();await page.locator('dialog [data-action="contacts"]').click();};
    const close=()=>page.locator('dialog [data-action="dismiss"]').click();
    const contact=()=>page.getByLabel('Телефон или email',{exact:true});
    const resume=async id=>{await menu();await page.locator('dialog [data-action="history"]').click();await page.locator(`[data-session="${id}"]`).click();await page.locator('dialog [data-action="resume"]').click();await idle();assert.equal(await activeID(),id);};

    await page.goto(base+'/consultation.html?start=new');await idle();
    result.first_session=await activeID();
    await snap('01-welcome-desktop');
    await button('Оставить заявку специалисту').click();
    await button('Проверить заявку').click();
    assert.equal(await contact().getAttribute('aria-invalid'),'true');
    assert.equal(await page.getByLabel('Кратко о вашей задаче').getAttribute('aria-invalid'),'true');
    assert.equal(await page.evaluate(()=>document.activeElement.name),'contact');
    await contact().fill('audit@localhost');
    const description='Тестовая заявка аудита интерфейса: нужен раздельный учёт электричества в офисе и на складе. Реальный звонок не требуется.';
    await page.getByLabel('Кратко о вашей задаче').fill(description);
    await button('Проверить заявку').click();
    assert.equal(await contact().getAttribute('aria-invalid'),'true');
    await snap('02-invalid-contact');
    await contact().fill('+7 999 000 11 22');
    await page.getByLabel('Имя и фамилия',{exact:true}).fill('Тестовый пользователь аудита');
    await page.getByLabel('Название компании',{exact:true}).fill('Демо — проверка интерфейса');
    await page.locator('input[value="scheduled"]').check();
    await page.getByLabel('Дата звонка',{exact:true}).fill('2020-01-01');
    await page.getByLabel('Время звонка · МСК',{exact:true}).fill('14:30');
    await button('Проверить заявку').click();
    assert.equal(await page.getByLabel('Дата звонка',{exact:true}).getAttribute('aria-invalid'),'true');
    const tomorrow=new Date(Date.now()+86400000).toISOString().slice(0,10);
    await page.getByLabel('Дата звонка',{exact:true}).fill(tomorrow);
    await page.setViewportSize({width:320,height:760});
    await page.locator('.et-callback').scrollIntoViewIfNeeded();
    await snap('03-callback-mobile-320');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await contact().fill('audit-ui@example.test');
    assert.equal(await page.locator('.et-callback').isVisible(),false);
    await page.reload();await page.locator('.et-contact-form').waitFor();
    assert.equal(await contact().inputValue(),'audit-ui@example.test');
    const summaryEditable=await page.locator('.et-contact-form [name="summary"]').count();
    assert.equal(summaryEditable,1,'a manually entered task remains editable after reload');
    assert.equal(await page.getByLabel('Кратко о вашей задаче').inputValue(),description);
    assert.equal(await button('Предыдущая переписка').count(),0,'do not offer an empty transcript');
    result.observations.push({scenario:'reload welcome form',summary_editable:summaryEditable===1,attachment_label:await page.locator('.et-attachment').count() ? await page.locator('.et-attachment').innerText() : null});
    await snap('04-contact-reloaded-mobile');
    await button('Вернуться к консультации').click();await idle();
    await input.fill('Черновик первого диалога: учёт офиса');
    await menu();await page.locator('dialog [data-action="new"]').click();await page.locator('dialog [data-action="confirm-new"]').click();await idle();
    result.second_session=await activeID();
    await input.fill('Черновик второго диалога: учёт склада');
    await menu();await page.locator('dialog [data-action="history"]').click();
    await page.locator('dialog [data-session]').first().waitFor();
    const titles=await page.locator('dialog .et-card h2').allTextContents();
    assert.equal(new Set(titles).size,2,'draft-only sessions have recognizable distinct titles');
    assert.ok(titles.includes('Черновик первого диалога: учёт офиса'));
    assert.ok(titles.includes('Черновик второго диалога: учёт склада'));
    result.observations.push({scenario:'draft-only history titles',titles});
    await snap('05-draft-history-mobile');
    await close();
    await resume(result.first_session);
    assert.equal(await input.inputValue(),'Черновик первого диалога: учёт офиса');
    await contacts();assert.equal(await contact().inputValue(),'audit-ui@example.test');
    await button('Проверить заявку').click();
    await page.getByRole('heading',{name:'Проверьте заявку',exact:true}).waitFor();
    assert.match(await page.locator('.et-review').innerText(),/audit-ui@example.test/);
    assert.doesNotMatch(await page.locator('.et-review').innerText(),/999 000 11 22/);
    assert.match(await page.locator('.et-review').innerText(),/Ответ по электронной почте/);
    await page.reload();await page.getByRole('heading',{name:'Проверьте заявку',exact:true}).waitFor();
    await button('Изменить данные').click();
    await contact().fill('cancelled@example.test');await button('Отмена').click();
    assert.doesNotMatch(await page.locator('.et-review').innerText(),/cancelled@example/);
    await button('Вернуться к консультации').click();await idle();
    assert.equal(await input.inputValue(),'Черновик первого диалога: учёт офиса');
    await contacts();await button('Продолжить без контакта').click();await button('Продолжить консультацию').click();await idle();
    assert.equal(await input.inputValue(),'Черновик первого диалога: учёт офиса');
    await contacts();await button('Проверить заявку').click();
    await button('Сформировать заявку').click();
    await page.getByRole('heading',{name:'Заявка сформирована',exact:true}).waitFor();
    result.application_number=await page.locator('.et-review .et-application-number').innerText();
    await snap('06-saved-mobile-320');
    const download=page.waitForEvent('download');
    await button('Скачать заявку').click();await (await download).saveAs(path.join(out,'application.txt'));
    const saved=await (await page.request.get(base+'/api/v1/sessions/'+result.first_session)).json();
    assert.equal(saved.demo,true);
    assert.equal(saved.application.email,'audit-ui@example.test');
    assert.equal(saved.application.phone,'');
    assert.equal(saved.application.summary,description);
    result.application_id=saved.application.id;
    const manager=await browser.newPage({viewport:{width:1440,height:960}});
    try {
      await manager.goto(base+'/applications.html?id='+encodeURIComponent(result.application_id));
      await manager.getByText('audit-ui@example.test',{exact:true}).waitFor();
      const record=await(await manager.request.get(base+'/api/v1/applications/'+result.application_id)).json();
      assert.equal(record.card.contact_time.value,'','email does not imply a telephone callback time');
      assert.equal(record.card.contact_time.status,'unknown');
      await manager.locator('#application').screenshot({path:path.join(out,'09-manager-application.png')});
      await manager.getByRole('button',{name:'Взять в работу',exact:true}).click();
      await manager.getByRole('button',{name:'Принять в работу',exact:true}).click();
      await manager.getByRole('button',{name:'Открыть повторно',exact:true}).waitFor();
      await menu();await button('Изменить контакты').click();
      await page.getByLabel('Имя и фамилия',{exact:true}).fill('Попытка изменения принятой заявки');
      const responsePromise=page.waitForResponse(r=>r.url().endsWith('/application')&&r.request().method()==='POST');
      await button('Сохранить').click();
      const response=await responsePromise,error=await response.json();
      assert.equal(response.status(),409);
      assert.equal(error.code,'application_closed');
      await page.locator('.et-modal-error').waitFor();
      assert.match(await page.locator('.et-modal-error').innerText(),/Дополнения можно написать в консультации/);
      const errorBox=await page.locator('.et-modal-error').boundingBox();
      assert.ok(errorBox.y>=0&&errorBox.y+errorBox.height<=page.viewportSize().height+1,'mobile error explanation is fully visible after save');
      await snap('10-decided-application-help');
      await button('Отмена').click();
      result.manager_review={taken_into_review:true,accepted:true,client_edit_status:response.status(),client_edit_code:error.code};
    } finally {
      const reopen=manager.getByRole('button',{name:'Открыть повторно',exact:true});
      if(await reopen.isVisible()) {
        await reopen.click();
        await manager.locator('dialog select[name="reason"]').selectOption('manager_error');
        await manager.locator('dialog textarea[name="comment"]').fill('Живой аудит завершён; тестовая заявка возвращена в разбор.');
        await manager.locator('dialog').getByRole('button',{name:'Открыть повторно',exact:true}).click();
        await manager.getByRole('button',{name:'Принять в работу',exact:true}).waitFor();
      }
      await manager.close();
    }
    await page.setViewportSize({width:390,height:480});
    await button('Продолжить консультацию').click();await idle();await input.focus();await input.scrollIntoViewIfNeeded();
    const box=await input.boundingBox();assert.ok(box.y>=0&&box.y+box.height<=480);
    await snap('07-short-mobile-composer');
    await menu();await page.getByRole('button',{name:'Вернуться на сайт',exact:true}).click();await page.locator('dialog [data-action="confirm-close"]').click();
    await page.waitForURL(url=>url.pathname!=='/consultation.html');
    await page.goto(base+'/consultation.html');await idle();assert.equal(await activeID(),result.first_session);
    assert.equal(await input.inputValue(),'Черновик первого диалога: учёт офиса');
    await resume(result.second_session);assert.equal(await input.inputValue(),'Черновик второго диалога: учёт склада');
    await resume(result.first_session);await page.setViewportSize({width:1440,height:960});
    await menu();await page.locator('dialog [data-action="application"]').click();await snap('08-saved-desktop');
    result.scenarios=['welcome form','empty/invalid contact validation','scheduled callback validation','phone to email replacement','reload contacts/review','per-session composer drafts','draft history','edit cancellation','review to chat','decline to chat','save and TXT download','site return','mobile 320/390 and short viewport','own application in manager queue','email callback display','manager accept/reopen','client edit after manager decision'];
    assert.equal(result.llm_requests,0);
    assert.deepEqual(result.errors,[]);
    result.passed=true;
  } catch(e) {result.passed=false;result.failure=e.stack;throw e;}
  finally {result.finished_at=new Date().toISOString();fs.writeFileSync(path.join(out,'result.json'),JSON.stringify(result,null,2));await browser.close();}
  console.log('PASS: live alternative user journeys, no API mocks, no LLM calls. '+path.join(out,'result.json'));
})().catch(e=>{console.error(e);process.exitCode=1;});
