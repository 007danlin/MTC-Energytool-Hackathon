// Read-only live UI follow-up: uses an existing synthetic audit session, no LLM calls.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.WEB_TEST_URL||'http://127.0.0.1:8768';
const sessionID=process.env.WEB_TEST_SESSION||'cab095ba-f5f4-4e61-953a-d350491ea435';
const out=process.env.WEB_TEST_SHOTS||'reports/live-user-audit-20261115/followup-actions';
if(!/^http:\/\/(127\.0\.0\.1|localhost):/.test(base))throw Error('Local audit only');
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true});
 const result={started_at:new Date().toISOString(),base,session_id:sessionID,scenarios:[],screenshots:[],mutations:[],errors:[]};
 try {
  const page=await browser.newPage({viewport:{width:1440,height:960},locale:'ru-RU'});
  page.on('pageerror',error=>result.errors.push(error.message));
  page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/')&&!['GET','HEAD'].includes(r.method()))result.mutations.push({method:r.method(),url:r.url()});});
  await page.addInitScript(id=>{localStorage.setItem('energytool-session',id);localStorage.setItem('energytool-session-ids',JSON.stringify([id]));},sessionID);
  const ready=()=>page.waitForFunction(()=>{const q=document.querySelector('#et-question'),h=document.querySelector('#energytool-chat');return q&&!q.disabled&&!['waiting','sync'].includes(h.dataset.screen);});
  const snap=async name=>{await page.evaluate(()=>document.fonts.ready);const file=path.join(out,name+'.png');await page.screenshot({path:file});result.screenshots.push(file);};
  const close=()=>page.locator('dialog [data-action="dismiss"]').click();
  const before=await(await page.request.get(base+'/api/v1/sessions/'+sessionID)).json();
  assert.equal(before.id,sessionID);assert.equal(before.status,'active');
  result.message_count=before.messages.length;
  await page.goto(base+'/consultation.html');await ready();
  const desktopPlan=page.locator('.et-plan-sidebar [data-plan-step]');
  result.plan_steps=await desktopPlan.count();assert.ok(result.plan_steps>0,'the live recommendation has an action plan');
  await desktopPlan.first().check();
  assert.equal(await desktopPlan.first().isChecked(),true);
  await snap('01-desktop-plan-checked');
  await page.reload();await ready();
  assert.equal(await desktopPlan.first().isChecked(),true,'plan check survives reload');
  await page.locator('.et-plan-sidebar [data-action="plan-source"]').click();
  await page.getByRole('heading',{name:'Ответ, из которого собран план',exact:true}).waitFor();
  const sourceAnswer=await page.locator('dialog .et-message-body').innerText();
  assert.ok(before.messages.some(m=>m.role==='assistant'&&m.content===sourceAnswer),'source is an actual live answer');
  await snap('02-plan-source');await close();
  await page.locator('.et-sidebar [data-action="task-add"]').click();
  await page.getByLabel('Куда добавить',{exact:true}).selectOption('constraints');
  const unsent='Аудит черновика: планируем проверку без остановки работы кафе';
  await page.getByLabel('Дополнение к задаче',{exact:true}).fill(unsent);
  await page.getByRole('button',{name:'Добавить в черновик',exact:true}).click();
  const draft=await page.locator('#et-question').inputValue();
  assert.match(draft,/Дополнение — условия:/);assert.match(draft,/без остановки работы кафе/);
  assert.doesNotMatch(await page.locator('.et-sidebar .et-task-rows').innerText(),/Аудит черновика/,'unsent fact must not become a confirmed task');
  await page.reload();await ready();
  assert.equal(await page.locator('#et-question').inputValue(),draft);
  assert.equal(await desktopPlan.first().isChecked(),true);
  await snap('03-draft-persisted');
  await page.setViewportSize({width:390,height:844});
  await page.locator('.et-task-mobile').click();
  await page.getByRole('heading',{name:'Ваша задача в фокусе',exact:true}).waitFor();
  assert.doesNotMatch(await page.locator('dialog .et-task-rows').innerText(),/Аудит черновика/);
  assert.equal(await page.locator('dialog').evaluate(e=>e.scrollWidth>e.clientWidth+1),false);
  await snap('04-mobile-task');await close();
  assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('et-task-mobile')),true);
  await page.locator('.et-plan-toggle').click();
  assert.equal(await page.locator('dialog [data-plan-step]').first().isChecked(),true);
  await page.locator('dialog [data-action="plan-source"]').click();
  await page.getByRole('heading',{name:'Ответ, из которого собран план',exact:true}).waitFor();
  assert.equal(await page.locator('dialog .et-message-body').innerText(),sourceAnswer);
  await snap('05-mobile-plan-source');await close();
  await page.getByRole('button',{name:'Меню',exact:true}).click();
  await page.getByRole('button',{name:'Включить режим отладки',exact:true}).click();
  const sourceButtons=page.locator('[data-source-message]');
  assert.ok(await sourceButtons.count()>0);
  await sourceButtons.last().click();await page.getByRole('heading',{name:'Источники и время',exact:true}).waitFor();
  result.source_fragments=await page.locator('dialog [data-fragment]').count();
  await snap('06-mobile-sources');
  if(result.source_fragments){
    await page.locator('dialog [data-fragment]').first().click();
    assert.ok((await page.locator('dialog .et-source-quote').innerText()).length>0);
    await snap('07-mobile-quote');
    await page.getByRole('button',{name:'Назад к источникам',exact:true}).click();
    await page.getByRole('heading',{name:'Источники и время',exact:true}).waitFor();
  }
  await close();
  assert.equal(await page.locator('#et-question').inputValue(),draft);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.locator('#et-question').scrollIntoViewIfNeeded();await snap('08-mobile-final-draft');
  const after=await(await page.request.get(base+'/api/v1/sessions/'+sessionID)).json();
  assert.deepEqual(after.messages,before.messages,'follow-up controls did not alter the live server conversation');
  assert.deepEqual(result.mutations,[],'all interactions are local-only');assert.deepEqual(result.errors,[]);
  result.scenarios=['live action plan checkbox','checkbox persists on reload','plan source matches live answer','add fact only to draft','draft persists on reload','unsent fact not confirmed','mobile task and focus return','mobile plan and source','debug sources and quote navigation','mobile composer preserves draft'];
  result.passed=true;
 }catch(e){result.passed=false;result.failure=e.stack;throw e;}
 finally{result.finished_at=new Date().toISOString();fs.writeFileSync(path.join(out,'result.json'),JSON.stringify(result,null,2));await browser.close();}
 console.log('PASS: read-only live follow-up actions; '+path.join(out,'result.json'));
})().catch(e=>{console.error(e);process.exitCode=1;});
