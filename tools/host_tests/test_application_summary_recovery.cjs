// Deterministic handoff regressions; the live model is not called by this suite.
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WEB_TEST_URL || 'http://127.0.0.1:8768';

(async () => {
  const browser = await chromium.launch({headless:true});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844}});
    const errors = [];
    page.on('pageerror', error=>errors.push(error.message));
    const sessions = {};
    const applications = [];
    let count = 0, seeded = false, held = null;
    const answer = (session, facts=[]) => {
      const response = {status:'answered',answer:'Начните с раздельного учёта по арендаторам.',sources:[],
        summary:{state_version:2,task:[{value:'Раздельный учёт арендаторов'}],object:[{value:'Офис'}],parameters:facts.map(value=>({value}))}};
      session.messages.push({role:'assistant',content:response.answer,response});
      session.last_result = response;
    };
    await page.route('**/api/v1/**', async route=>{
      const req=route.request(), parts=new URL(req.url()).pathname.split('/').filter(Boolean);
      let response;
      if (parts.length===3 && req.method()==='POST') {
        const id='summary-recovery-'+(++count);
        response=sessions[id]={id,status:'active',messages:[],lead:{fields:{}},updated_at:new Date().toISOString()};
        if (seeded) { response.messages.push({role:'user',content:'Нужен раздельный учёт арендаторов офиса.'}); answer(response); }
      } else if (parts.length===3) response={sessions:Object.values(sessions)};
      else {
        const session=sessions[parts[3]];
        assert.ok(session,'unexpected session');
        if (parts[4]==='messages') {
          session.messages.push({role:'user',content:req.postDataJSON().content});
          await new Promise(resolve=>{held=resolve;});
          answer(session,['Круглосуточный режим','Шесть арендаторов','Площадь 1500 м²']);
          response=session.last_result;
        } else if (parts[4]==='application') {
          const body=req.postDataJSON(); applications.push(body);
          session.application={...body,id:'ET-'+session.id,number:'100001',saved_at:new Date().toISOString()};
          response=session;
        } else response=session;
      }
      await route.fulfill({json:response});
    });
    const ready=()=>page.waitForFunction(()=>!['waiting','sync'].includes(document.querySelector('#energytool-chat').dataset.screen)&&!document.querySelector('#et-question').disabled);
    const button=name=>page.getByRole('button',{name,exact:true});
    const fresh=async()=>{await page.goto(base+'/consultation.html?start=new');await ready();return sessions[await page.evaluate(()=>localStorage.getItem('energytool-session'))];};
    const close=()=>page.locator('dialog').getByRole('button',{name:'Закрыть',exact:true}).click();
    const prepare=async()=>{await button('Меню').click();await page.locator('dialog').getByRole('button',{name:'Подготовить заявку',exact:true}).click();};
    const description=()=>page.getByLabel('Кратко о вашей задаче',{exact:true});

    // A manually entered description stays editable after reload and navigation.
    await fresh(); await button('Оставить заявку специалисту').click();
    assert.equal(await button('Предыдущая переписка').count(),0,'empty transcript is not offered');
    await page.getByLabel('Телефон или email',{exact:true}).fill('manual@example.test');
    const manual='Помогите организовать учёт на складе. Это моё описание.';
    await description().fill(manual);
    await page.reload(); await description().waitFor();
    assert.equal(await description().inputValue(),manual);
    assert.equal(await page.getByText('Описание задачи из нашей беседы',{exact:true}).count(),0);
    await button('Проверить заявку').click();
    assert.match(await page.locator('.et-review').innerText(),/Это моё описание/);
    assert.equal(await button('Предыдущая переписка').count(),0);
    await button('Вернуться к консультации').click(); await prepare();
    assert.equal(await description().inputValue(),manual);

    // Reopening an autogenerated draft refreshes only its description, not contact fields.
    seeded=true;
    const session=await fresh(); await prepare();
    await page.getByLabel('Телефон или email',{exact:true}).fill('conversation@example.test');
    await button('Вернуться к консультации').click();
    session.messages.push({role:'user',content:'Режим работы офиса круглосуточный.'});
    answer(session,['Круглосуточный режим']);
    await page.reload(); await ready(); await prepare();
    assert.equal(await page.getByLabel('Телефон или email',{exact:true}).inputValue(),'conversation@example.test');
    await button('Посмотреть').click();
    assert.match(await page.locator('dialog').innerText(),/Круглосуточный режим/);
    await close();

    // Explicit edits are not overwritten by later conversation summaries.
    await button('Проверить заявку').click(); await button('Изменить данные').click();
    await page.locator('.et-summary-edit summary').click();
    const edited='Согласованное вручную описание для оператора.';
    await description().fill(edited); await button('Сохранить').click();
    await button('Вернуться к консультации').click();
    session.messages.push({role:'user',content:'Уточнение: шесть арендаторов.'});
    answer(session,['Круглосуточный режим','Шесть арендаторов']);
    await page.reload(); await ready(); await prepare();
    assert.equal(await description().inputValue(),edited);
    assert.equal(await page.getByLabel('Телефон или email',{exact:true}).inputValue(),'conversation@example.test');

    // A new plain-text question is handed off even while the old summary is still current.
    const pending=await fresh();
    const latest='Дополнительно: шесть арендаторов и площадь 1500 м².';
    await page.locator('#et-question').fill(latest); await page.locator('.et-send').click();
    await button('Прервать ожидание').waitFor();
    await page.waitForFunction(()=>document.querySelector('#energytool-chat').dataset.screen==='waiting');
    await button('Прервать ожидание').click(); await button('Позвать оператора').click();
    await button('Посмотреть').click();
    const summary=await page.locator('dialog .et-application-summary').innerText();
    assert.match(summary,/Последние уточнения клиента/);
    assert.ok(summary.includes(latest),'pending natural-language facts must not be lost');
    assert.equal(summary.split(latest).length-1,1,'pending question appears only once');
    await close();
    await page.getByLabel('Телефон или email',{exact:true}).fill('pending@example.test');
    await button('Проверить заявку').click(); await button('Сформировать заявку').click();
    await page.getByRole('heading',{name:'Заявка сформирована',exact:true}).waitFor();
    assert.ok(pending.application.summary.includes(latest));
    assert.equal(Object.hasOwn(applications.at(-1),'summary_source'),false,'UI draft metadata is not sent to the API');
    held();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    console.log('PASS: manual summary remains editable across reload; regenerated summary follows newer facts; manual edits preserved; pending plain-text facts included once; contacts retained; empty transcript hidden.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
