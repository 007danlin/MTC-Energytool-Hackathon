def quote(text, limit=600):
    body = text.split('\n', 1)
    head, rest = body[0], (body[1] if len(body) > 1 else '')
    rest = ' '.join(rest.split())
    if len(rest) > limit:
        rest = rest[:limit].rsplit(' ', 1)[0] + ' …'
    return f'**{head}**  \n{rest}'


def q_block(question):
    lines = question.splitlines()
    if len(lines) == 1:
        return f'> {question}'
    return '\n'.join(f'> {l}  ' for l in lines)


